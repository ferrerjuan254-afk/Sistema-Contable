def cargar_puc(session: Session, empresa_id: int, sobrescribir: bool = False) -> int:
    """
    Carga el PUC colombiano para una empresa.

    Args:
        session:     Sesión SQLAlchemy activa.
        empresa_id:  ID de la empresa destino.
        sobrescribir: Si True, elimina el PUC existente antes de cargar.

    Returns:
        Número de cuentas insertadas.
    """
    if sobrescribir:
        session.query(PlanCuenta).filter_by(empresa_id=empresa_id).delete()
        session.flush()

    # Verificar si ya existe PUC para la empresa
    existente = session.query(PlanCuenta).filter_by(empresa_id=empresa_id).count()
    if existente > 0 and not sobrescribir:
        return 0

    nivel_acepta = {1: False, 2: False, 3: False, 4: True}

    cuentas = []
    for codigo, nombre, naturaleza, tipo, nivel, padre in PUC_DATA:
        cuenta = PlanCuenta(
            empresa_id   = empresa_id,
            codigo       = codigo,
            nombre       = nombre,
            naturaleza   = NaturalezaCuenta(naturaleza),
            tipo         = TipoCuenta(tipo),
            nivel        = nivel,
            cuenta_padre = padre,
            acepta_mov   = nivel_acepta.get(nivel, True),
            activa       = True,
        )
        cuentas.append(cuenta)

    session.bulk_save_objects(cuentas)
    session.commit()
